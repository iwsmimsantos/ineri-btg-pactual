-- 5) Assessores (com categoria_assessor ENUM)
CREATE TABLE assessores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    categoria_assessor categoria_assessor NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    ativo BOOLEAN NOT NULL
);

-- 6) Ativos
CREATE TABLE ativos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    preco_atual NUMERIC(18,2) NOT NULL,
    risco NUMERIC(5,2) NOT NULL,
    rentabilidade NUMERIC(5,2) NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    ativo BOOLEAN NOT NULL
);

-- 7) Clientes
CREATE TABLE clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    data_nascimento TIMESTAMP WITH TIME ZONE NOT NULL,
    assessor_id INTEGER NOT NULL
        REFERENCES assessores(id) ON DELETE RESTRICT,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    ativo BOOLEAN NOT NULL
);

-- 8) Histórico de risco calculado
CREATE TABLE historico_risco_calculado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL
        REFERENCES clientes(id) ON DELETE CASCADE,
    risco_calculado INTEGER NOT NULL,
    dados_calculo JSONB NOT NULL,
    data_calculo TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 9) Histórico de risco declarado
CREATE TABLE historico_risco_declarado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL
        REFERENCES clientes(id) ON DELETE CASCADE,
    risco_declarado INTEGER NOT NULL,
    respostas_questionario JSONB NOT NULL,
    data_declaracao TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 10) Investimento
CREATE TABLE investimento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL
        REFERENCES clientes(id) ON DELETE CASCADE,
    ativo_id INTEGER NOT NULL
        REFERENCES ativos(id) ON DELETE RESTRICT,
    quantidade NUMERIC(18,6) NOT NULL,
    preco_compra NUMERIC(18,2) NOT NULL,
    data_compra TIMESTAMP WITH TIME ZONE NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 11) Recomendações (mantendo status como ENUM)
CREATE TABLE recomendacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL
        REFERENCES clientes(id) ON DELETE CASCADE,
    ativo_id INTEGER NOT NULL
        REFERENCES ativos(id) ON DELETE RESTRICT,
    descricao VARCHAR(500) NOT NULL,
    quantidade_sugerida NUMERIC(18,6) NOT NULL,
    status_recomendacao status_recomendacao NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    data_atualizacao TIMESTAMP WITH TIME ZONE
);

