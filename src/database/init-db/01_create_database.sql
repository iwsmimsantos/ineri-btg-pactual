-- 1) Cria tipos ENUM para categoria de assessor e status de recomendação
DO $$
BEGIN

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'categoria_assessor') THEN
    CREATE TYPE categoria_assessor AS ENUM ('Gold','Prata','Platinum');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'status_recomendacao') THEN
    CREATE TYPE status_recomendacao AS ENUM ('pendente','aceita','rejeitada');
  END IF;
END
$$;

