-- Função de limpeza/validação de CPF
CREATE OR REPLACE FUNCTION valida_cpf() RETURNS TRIGGER AS $$
BEGIN
  NEW.cpf := regexp_replace(NEW.cpf,'[^0-9]','','g');
  IF length(NEW.cpf) <> 11 THEN
    RAISE EXCEPTION 'CPF deve ter 11 dígitos';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_valida_cpf_clientes
  BEFORE INSERT OR UPDATE ON clientes
  FOR EACH ROW EXECUTE FUNCTION valida_cpf();

-- Validação de email simples
CREATE OR REPLACE FUNCTION valida_email() RETURNS TRIGGER AS $$
BEGIN
  IF NEW.email NOT LIKE '%@%.%' THEN
    RAISE EXCEPTION 'Email inválido';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_valida_email_clientes
  BEFORE INSERT OR UPDATE ON clientes
  FOR EACH ROW EXECUTE FUNCTION valida_email();

CREATE TRIGGER trg_valida_email_assessores
  BEFORE INSERT OR UPDATE ON assessores
  FOR EACH ROW EXECUTE FUNCTION valida_email();

-- Impede exclusão de assessor com clientes vinculados
CREATE OR REPLACE FUNCTION protege_assessor() RETURNS TRIGGER AS $$
DECLARE ccount INT;
BEGIN
  SELECT COUNT(*) INTO ccount FROM clientes WHERE assessor_id = OLD.id;
  IF ccount>0 THEN
    RAISE EXCEPTION 'Assessor tem % cliente(s) vinculado(s)', ccount;
  END IF;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_protege_assessor
  BEFORE DELETE ON assessores
  FOR EACH ROW EXECUTE FUNCTION protege_assessor();

-- Impede exclusão de cliente com investimentos
CREATE OR REPLACE FUNCTION protege_cliente_com_investimentos() RETURNS TRIGGER AS $$
DECLARE icount INT;
BEGIN
  SELECT COUNT(*) INTO icount FROM investimento WHERE cliente_id=OLD.id;
  IF icount>0 THEN
    RAISE EXCEPTION 'Cliente possui % investimento(s) ativo(s)', icount;
  END IF;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_protege_cliente_investimento
  BEFORE DELETE ON clientes
  FOR EACH ROW EXECUTE FUNCTION protege_cliente_com_investimentos();

-- Impede exclusão de ativo presente em investimento
CREATE OR REPLACE FUNCTION protege_ativo_com_investimentos() RETURNS TRIGGER AS $$
DECLARE acount INT;
BEGIN
  SELECT COUNT(*) INTO acount FROM investimento WHERE ativo_id=OLD.id;
  IF acount>0 THEN
    RAISE EXCEPTION 'Ativo está presente em % investimento(s)', acount;
  END IF;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_protege_ativo_investimento
  BEFORE DELETE ON ativos
  FOR EACH ROW EXECUTE FUNCTION protege_ativo_com_investimentos();

-- Função para transferir cliente de assessor
CREATE OR REPLACE FUNCTION transferir_cliente(
  p_cliente_id INT, p_novo_assessor_id INT) RETURNS VOID AS $$
BEGIN
  UPDATE clientes
    SET assessor_id = p_novo_assessor_id
  WHERE id = p_cliente_id;
END;
$$ LANGUAGE plpgsql;

-- Função que retorna total investido por cliente
CREATE OR REPLACE FUNCTION total_investido_cliente(p_cliente_id INT)
  RETURNS NUMERIC AS $$
DECLARE total NUMERIC;
BEGIN
  SELECT COALESCE(SUM(quantidade * preco_compra),0) INTO total
    FROM investimento WHERE cliente_id = p_cliente_id;
  RETURN total;
END;
$$ LANGUAGE plpgsql;

-- Função que lista clientes sem contato em X dias
CREATE OR REPLACE FUNCTION clientes_sem_contato(dias INT DEFAULT 30)
  RETURNS TABLE(id INT,nome VARCHAR,ultimo_contato TIMESTAMP) AS $$
BEGIN
  RETURN QUERY
    SELECT c.id,c.nome,NULL  -- este esquema não armazena ultimo_contato
    FROM clientes c
    ORDER BY c.data_criacao ASC;
END;
$$ LANGUAGE plpgsql;

-- Função para criar recomendação (gera ID automático)
CREATE OR REPLACE FUNCTION criar_recomendacao(
  p_cliente_id INT,p_ativo_id INT,p_descricao TEXT) RETURNS VOID AS $$
BEGIN
  INSERT INTO recomendacoes(cliente_id,ativo_id,descricao,status_recomendacao,
    data_criacao)
  VALUES (p_cliente_id,p_ativo_id,p_descricao,'pendente',NOW());
END;
$$ LANGUAGE plpgsql;

-- Procedure para atualizar status de recomendação
CREATE OR REPLACE PROCEDURE atualizar_status_recomendacao(
  p_recomendacao_id INT, p_novo_status status_recomendacao)
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE recomendacoes
    SET status_recomendacao = p_novo_status,
        data_atualizacao  = NOW()
  WHERE id = p_recomendacao_id;
END;
$$;
